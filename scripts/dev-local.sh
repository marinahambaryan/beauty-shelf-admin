#!/usr/bin/env bash
# Runs the console on this Mac against the LOCAL Supabase stack. It never touches the hosted
# project. Needs OrbStack or Docker running, and ../beauty-shelf next to this folder.
#   1. starts the stack if needed and applies new migrations (existing data stays)
#   2. serves the admin-users function
#   3. points .env.local at the stack, adds a local admin and two products to review
#   4. installs dependencies and starts the console on http://localhost:3100
# Safe to re-run. Usage:  npm run dev:local
set -euo pipefail
ADMIN_DIR="$(cd "$(dirname "$0")/.." && pwd)"
APP_DIR="$ADMIN_DIR/../beauty-shelf"

step() { printf '\n\033[1;35m▸ %s\033[0m\n' "$1"; }
fail() { printf '\n\033[1;31m✗ %s\033[0m\n' "$1" >&2; exit 1; }

[ -d "$APP_DIR/supabase" ] || fail "Couldn't find ../beauty-shelf next to this folder."
docker info >/dev/null 2>&1 || fail "Docker isn't running. Open OrbStack, wait until it's ready, then re-run."

cd "$APP_DIR"
step "Starting local Supabase"
npx supabase status >/dev/null 2>&1 || npx supabase start

step "Applying new migrations"
npx supabase migration up

STATUS_ENV=$(npx supabase status -o env 2>/dev/null)
get() { printf '%s\n' "$STATUS_ENV" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -n1; }
API_URL=$(get API_URL)
ANON_KEY=$(get ANON_KEY)
[ -n "$ANON_KEY" ] || ANON_KEY=$(get PUBLISHABLE_KEY)
[ -n "$API_URL" ] && [ -n "$ANON_KEY" ] || fail "Couldn't read the API URL and key from 'supabase status'."
case "$API_URL" in
  http://127.0.0.1:*|http://localhost:*) ;;
  *) fail "Expected a local API URL, got $API_URL." ;;
esac

step "Serving the admin-users function"
FUNCTIONS_LOG="$ADMIN_DIR/.functions.log"
npx supabase functions serve admin-users >"$FUNCTIONS_LOG" 2>&1 &
FUNCTIONS_PID=$!
trap 'kill "$FUNCTIONS_PID" 2>/dev/null || true' EXIT
echo "Log: $FUNCTIONS_LOG"

cd "$ADMIN_DIR"
step "Pointing .env.local at the local stack"
cat > .env.local <<ENV
# Generated by scripts/dev-local.sh for the LOCAL Supabase stack.
NEXT_PUBLIC_SUPABASE_URL=$API_URL
NEXT_PUBLIC_SUPABASE_ANON_KEY=$ANON_KEY
ENV

step "Adding the local admin and products to review"
ADMIN_ID=$(node scripts/local-accounts.mjs "$API_URL" "$ANON_KEY")
docker exec supabase_db_beauty-shelf psql -q -U postgres -d postgres \
  -c "insert into public.admins (user_id) values ('$ADMIN_ID') on conflict do nothing"

step "Installing dependencies"
npm install --no-audit --no-fund

printf '\n\033[1;32m✓ Sign in at http://localhost:3100\033[0m\n'
printf '  Email:     admin@beautyshelf.local\n  Password:  ShelfAdmin2026\n\n'
npx next dev --port 3100
